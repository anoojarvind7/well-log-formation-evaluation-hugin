"""Writes results/SUMMARY.md from the pipeline's tables.

Every number in the summary is read from a results/ table produced in the same
run, so the text cannot drift from the data.
"""
from __future__ import annotations

import datetime as dt

import numpy as np
import pandas as pd

from . import config as C
from .validation import MIN_R


def md(df: pd.DataFrame, floatfmt=".3f") -> str:
    return df.to_markdown(index=False, floatfmt=floatfmt)


def _f(x, nd=2):
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{nd}f}"


def _pct_table(mc: pd.DataFrame) -> pd.DataFrame:
    want = [("phie_net", "Avg PHIE, net (v/v)", 3), ("sw_pay", "Avg Sw, pay (v/v)", 3),
            ("pay_md", "Net pay (m MD)", 1), ("hc_column_m", "HC column PHIE*(1-Sw)*h (m)", 2),
            ("rw", "Rw (ohm.m)", 3)]
    rows = []
    for w in C.WELLS:
        for k, lab, nd in want:
            r = mc[(mc.well == w) & (mc.metric == k)].iloc[0]
            if r.n_valid == 0:
                cell = "no pay in any draw"
                rows.append({"Well": w, "Quantity": lab, "P90 (low)": cell, "P50": "", "P10 (high)": ""})
                continue
            note = "" if r.n_valid == C.MC["n_draws"] else f" ({r.n_valid} draws with pay)"
            rows.append({"Well": w, "Quantity": lab + note, "P90 (low)": _f(r.P90, nd), "P50": _f(r.P50, nd),
                         "P10 (high)": _f(r.P10, nd)})
    return pd.DataFrame(rows)


def write_summary(R: dict) -> None:
    s = R["summary"].set_index("well")
    inv = R["inventory"]
    tops = R["tops"].set_index("well")
    qc = R["qc"].set_index("well")
    agree = R["agreement"].set_index("well").agreement
    reg = R["rw_regional"].set_index("well")
    L = []
    a = L.append

    a("# Hugin Formation evaluation: results summary\n")
    a(f"_Generated by `python -m hugin.pipeline` on {dt.date.today().isoformat()}. "
      "Every number below is read from the CSVs in this folder; figures are in `figures/`._\n")
    a(f"Formation evaluation of {len(C.WELLS)} wells ({', '.join(C.WELLS)}) from the public FORCE 2020 "
      "dataset (Norwegian Continental Shelf). This is a portfolio study on public data, not field or "
      "industry work. The well logs, their light cleaning, the NPD formation labels and the lithology "
      "labels all come from FORCE 2020 (Bormann et al. 2020); the interpretation below is this "
      "repository's own and is kept separate from theirs.\n")

    # Headline
    a("## Headline\n")
    hl = s[["gross_md", "net_md", "pay_md", "ntg", "phie_net", "sw_pay", "rw"]].reset_index()
    hl.columns = ["Well", "Gross (m MD)", "Net (m)", "Net pay (m)", "N/G", "Avg PHIE net", "Avg Sw pay", "Rw (ohm.m)"]
    a(md(hl, ".3g").replace(" nan ", "   - "))
    a("\nBase case: Larionov (older rocks) Vsh, shale-corrected density-neutron PHIE, Simandoux Sw, "
      f"cutoffs Vsh <= {C.CUTOFFS['vsh']}, PHIE >= {C.CUTOFFS['phi']}, Sw <= {C.CUTOFFS['sw']}. "
      "Averages are thickness-weighted over net (PHIE) and pore-volume-weighted over pay (Sw). "
      "Wells are near-vertical (MD and TVD thickness agree to within 0.1 m).\n")

    paying = [w for w in C.WELLS if s.loc[w, "pay_md"] >= 2]
    wet = [w for w in C.WELLS if s.loc[w, "pay_md"] < 2]
    a("**Reading it:** " + (f"{' and '.join(paying)} carry hydrocarbons in the Hugin. " if paying else "")
      + (f"{' and '.join(wet)} are water-bearing (under 2 m of flagged pay, which does not survive "
         "scrutiny; see per-well notes). " if wet else "")
      + "The water-bearing wells are still useful: they anchor Rw and show the method does not "
        "invent pay where there is none.\n")

    # Per well notes
    a("## Per-well notes\n")
    for w in C.WELLS:
        r, t = s.loc[w], tops.loc[w]
        a(f"### {w}\n")
        lines = [
            f"Hugin {t.hugin_top_md:.1f}-{t.hugin_base_md:.1f} m MD ({t.gross_md_m:.1f} m), between "
            f"{t.overlying.rstrip('.')} and {t.underlying.rstrip('.')}. The steepest GR drop is "
            f"{t.offset_m:+.1f} m from the labelled top.",
            f"GR baselines {r.gr_clean:.0f} / {r.gr_shale:.0f} API (shale from {r.gr_shale_source.rstrip('.')}). "
            f"Mean Vsh {r.vsh_lin_mean:.2f} linear vs {r.vsh_larionov_mean:.2f} Larionov.",
            f"Rw {r.rw:.3f} ohm.m at an estimated {r.t_reservoir_c:.0f} degC ({r.rw_at_100c:.3f} at 100 degC), "
            + (f"{r.rw_note}." if isinstance(r.get("rw_note"), str)
               else f"from its own water leg {r.water_leg_md} m MD ({int(r.n_water_leg)} clean samples)."),
        ]
        if r.pay_md >= 2:
            lines.append(
                f"{r.pay_md:.1f} m net pay, average PHIE {r.phie_net:.3f}, Sw {r.sw_pay:.2f}. Lowest pay "
                f"sample {r.lowest_pay_md:.1f} m MD"
                + (f", first clean wet sand below it at {r.highest_wet_below_md:.1f} m MD, which brackets "
                   "the hydrocarbon-water contact (or the base of a transition zone)."
                   if pd.notna(r.highest_wet_below_md) else ".")
            )
            if pd.notna(r.dn_crossover_pay_frac):
                lines.append(
                    f"Density-neutron crossover (PHID exceeds PHIN by > 0.05) in {100 * r.dn_crossover_pay_frac:.0f} % "
                    "of pay samples: a light-hydrocarbon effect. Logs alone do not separate gas from light "
                    "oil here, so the fluid type is not claimed.")
        else:
            lines.append(
                f"Water-bearing: {r.pay_md:.1f} m flagged as pay, mean Simandoux Sw {r.sw_sim_mean:.2f}. "
                f"With the regional Rw of the other wells ({reg.loc[w, 'rw_regional']:.3f} ohm.m) it would be "
                f"{reg.loc[w, 'pay_md_regional_rw']:.1f} m, so the call does not hinge on Rw.")
        if w == "25/2-14":
            lines.append("Its whole Hugin was used as the water leg, which is circular for this well; the "
                         "regional-Rw check above is the independent test.")
        if w in qc.index and qc.loc[w, "bit_size_source"].startswith("assumed"):
            lines.append(f"No bit-size curve: {qc.loc[w, 'bit_size_source']}.")
        a("\n".join(f"- {x}" for x in lines) + "\n")

    # Uncertainty
    a("## Uncertainty (step 9)\n")
    a(f"{C.MC['n_draws']} Monte Carlo draws per well over m, n, Rw, matrix and fluid density, the neutron "
      "unit shift and both GR baselines (ranges in `hugin/config.py`). P90 is the low case (90 % chance of "
      "exceeding), P10 the high case. Cutoffs are held fixed here; their effect is in the sweep below.\n")
    a(md(_pct_table(R["mc"])))
    sens = R["sens"].pivot(index="input", columns="well", values="rank_corr_with_pay")[C.WELLS]
    sens = sens.reindex(sens.abs().max(axis=1).sort_values(ascending=False).index)
    a("\nWhat drives net pay (Spearman rank correlation of each input with net pay across draws; "
      "meaningless for wells with no pay):\n")
    a(md(sens.reset_index(), ".2f"))
    a("\nRw and the GR shale baseline dominate. m matters little because Rw is re-fitted on the water "
      "leg with the same m in every draw, so the two errors largely cancel where pay and water-leg "
      "porosities are similar. That cancellation is real physics of the Pickett method, not a reason "
      "to trust m=2.\n")

    # Cutoff sweep
    sw = R["sweep"]
    a("## Cutoff sensitivity (step 8)\n")
    rows = []
    for w in C.WELLS:
        x = sw[sw.well == w].pay_md
        rows.append(dict(Well=w, **{"Base pay (m)": s.loc[w, "pay_md"], "Min over sweep": x.min(),
                                    "Max over sweep": x.max()}))
    a(md(pd.DataFrame(rows), ".1f"))
    a(f"\nSweep: Vsh {C.SWEEP['vsh']}, PHIE {C.SWEEP['phi']}, Sw {C.SWEEP['sw']} (all "
      f"{len(C.SWEEP['vsh']) * len(C.SWEEP['phi']) * len(C.SWEEP['sw'])} combinations). The Sw cutoff "
      "moves pay the most; see `figures/cutoff_sweep.png`.\n")

    # Lithology
    a("## Lithology vs FORCE (step 4)\n")
    a(f"Agreement with the FORCE hand-picked lithology over the Hugin: {100 * agree['ALL']:.0f} % pooled ("
      + ", ".join(f"{w} {100 * agree[w]:.0f} %" for w in C.WELLS) + ").\n")
    a(R["confusion"].reset_index().to_markdown(index=False))
    a("\nWhere and why the two disagree:\n")
    a("- **Carbonate called, FORCE says sandstone.** These are dense, low-neutron, clean beds: "
      "calcite-cemented sandstone stringers. FORCE labels the rock (sandstone); the log rule labels the "
      "log response. Both are defensible; neither is reservoir.\n"
      "- **Shaly sand vs shale.** The largest block of disagreement. GR-only Vsh cannot see thin "
      "shale beds below log resolution, and the GR shale baseline is a judgement (see the Monte Carlo, "
      "where it is a top driver). FORCE geoscientists also had core and cuttings descriptions.\n"
      "- **PEF is not used.** Hugin sandstone reads "
      + ", ".join(f"{qc.loc[w, 'hugin_pef_median']:.1f}" for w in C.WELLS if pd.notna(qc.loc[w, "hugin_pef_median"]))
      + " b/e (well medians) against ~1.8 for quartz, most likely from barite in the mud. Using it would "
        "turn clean sand into carbonate.\n")

    # QC
    a("## QC (step 2)\n")
    m = R["masked"]
    a(f"{len(m)} masked intervals are listed in `02_qc_masked_intervals.csv` (nothing is dropped silently). "
      "Inside the Hugin itself, bad hole affects "
      + ", ".join(f"{w} {qc.loc[w, 'hugin_badhole_pct']:.1f} %" for w in C.WELLS)
      + " of samples; the washouts are in the surrounding shales. Spike counts are small because FORCE had "
        "already despiked the logs (their work, not this repository's).\n")
    u = R["units"]
    a(f"LAS units checked for {u.well.nunique()} wells: {int(u.ok.sum())}/{len(u)} curves carry the expected "
      "unit (g/cm3, m3/m3, ohm.m, gAPI, in, us/ft, b/e). NPHI is a fraction (v/v), not percent.\n")
    al = qc.loc[C.WELLS, [c for c in qc.columns if c.startswith("align_")]].reset_index()
    a("Depth alignment against GR (lagged correlation, 1 sample = 0.152 m):\n")
    a(md(al))
    a("\nOnly strong correlations can show an offset; the NPHI-GR pair is the meaningful one. No curve "
      "shift was applied: the reported offsets are within about 1 m and inconsistent between curves, "
      "which reads as lithology-driven correlation noise rather than a systematic depth error.\n")

    # Validation
    a("## Validation (step 10)\n")
    if R.get("core") is not None and len(R["core"]):
        cs = R["core"].set_index("well")
        byv = R["core_by_vsh"]
        allv = byv[byv.well == "ALL"].set_index("vsh_class")
        clean = allv.iloc[0]
        a(f"Log porosity vs {int(cs.n_compared.sum())} helium plug porosities inside the Hugin (RealPore "
          "core data, Zenodo 4419060; plugs without a helium value use the file's 'best of available'). "
          "Each well's core is tied to the log by sliding density porosity over +-5 m; positive bias means "
          "the log reads higher than core.\n")
        t = R["core"][["well", "n_compared", "shift_m", "shift_r", "shift_reliable", "mean_core_phi",
                       "bias_phit", "rmse_phit", "bias_phie", "rmse_phie"]]
        a(md(t))
        a("\nSplit by the log's own Vsh at each plug (all wells pooled):\n")
        a(md(allv.reset_index().drop(columns="well")))
        best_phit = [w for w in cs.index if abs(cs.loc[w, "bias_phit"]) <= 0.025]
        best_phie = [w for w in cs.index if abs(cs.loc[w, "bias_phie"]) <= 0.025]
        a("\n**What the core says:**\n")
        a(f"- In clean sand ({int(clean.n)} plugs) the logs are close: PHIT reads {clean.bias_phit:+.3f} and "
          f"PHIE {clean.bias_phie:+.3f} against core on average.\n"
          f"- PHIT agrees best in {', '.join(best_phit) or 'no well'}; PHIE agrees best in "
          f"{', '.join(best_phie) or 'no well'}. Core porosity sits between the two curves, as expected for "
          "helium porosity on cleaned, dried plugs.\n"
          "- As Vsh rises, PHIT reads increasingly high (shale-bound water raises the neutron) and PHIE reads "
          "low (the shale correction overshoots). Where the log calls the rock shaly, the plugs are still "
          "sand: plugs tend to be cut from the most competent sand, and thin sand beds sit below log resolution.\n")
        if "25/5-3" in cs.index:
            r53 = byv[(byv.well == "25/5-3")].set_index("vsh_class")
            a(f"- 25/5-3 is the clearest case of over-correction: plugs average {r53.iloc[0].mean_core_phi:.2f} in "
              f"sand the log calls clean, PHIT matches them ({cs.loc['25/5-3', 'bias_phit']:+.3f}) and PHIE is "
              f"{cs.loc['25/5-3', 'bias_phie']:+.3f} low. The GR there likely carries some feldspar or mica "
              "signal rather than clay, so GR-derived Vsh is too high. This makes the 25/5-3 pay estimate "
              "conservative (lower PHIE gives higher Simandoux Sw); no parameter was re-tuned to the core, so "
              "this stays an independent check.\n")
        rel = cs[cs.shift_reliable]
        a(f"- Core-to-log depth shifts are {cs.shift_m.min():+.1f} to {cs.shift_m.max():+.1f} m (positive: log "
          f"deeper than core), within normal driller-logger differences; {len(rel)} of {len(cs)} are supported by "
          f"a correlation of at least {MIN_R} and are inside the search window.\n")
        a("See `figures/core_vs_log.png` and `figures/core_depth_tracks.png`; plug-by-plug values are in "
          "`10_core_vs_log_matched.csv`.\n")
    else:
        a("**Core comparison not yet run.** The core plug file (Zenodo 4419060) was not available when "
          "this summary was generated. Place it with `python scripts/fetch_data.py --core` (or "
          "`--core-file PATH`) and rerun `make all`; the comparison, depth-shift search and "
          "`figures/core_vs_log.png` are produced automatically.\n")
    pub = R["published"]
    if len(pub):
        for _, p in pub.iterrows():
            a(f"- {p.well}: average PHIE in net {p.this_work_phie_net:.3f} vs {p.published} reported for "
              f"{p.what} ({p.source}). {'Inside' if p.inside else 'Outside'} the published range. This is a "
              "regional comparison: 15/9-13 is in the Sleipner/Volve area, not a Volve well.\n")
    a("- The FORCE lithology comparison in step 4 is the second independent check.\n")

    # Inventory
    a("## Well selection (step 1)\n")
    a(f"{len(inv)} FORCE wells have a Hugin Fm label. Curve completeness across the Hugin (%):\n")
    cols = ["well", "hugin_md_m", "GR_pct", "RHOB_pct", "NPHI_pct", "RDEP_pct", "PEF_pct", "BS_pct",
            "core_plugs_in_hugin", "selected"]
    t = inv[cols].copy()
    t["core_plugs_in_hugin"] = t.core_plugs_in_hugin.map(lambda v: "core file absent" if pd.isna(v) else int(v))
    a(md(t, ".1f"))
    a("\nSelected: the four strongest core candidates from the plan's first look (full GR/density/neutron/"
      "resistivity/PEF across the Hugin), giving two wells with pay and two water-bearing wells for Rw. "
      "25/7-2 (thickest Hugin) was left out: no PEF and ~4.4 km deep. 15/9-14 is used only as the Rw "
      "offset for 15/9-13.\n")

    a("## Assumptions that matter most\n")
    a("- a = 1, m = 2, n = 2: textbook values, no SCAL available (varied in the Monte Carlo).\n"
      f"- NPHI taken as limestone units and shifted +{C.NPHI_SS_SHIFT} v/v to sandstone (varied 0 to 0.06).\n"
      f"- Fluid density {C.RHO_FLUID} g/cc; mud type unknown (varied 0.9-1.1).\n"
      f"- Temperature {C.SEABED_T_C} degC at seabed + {C.GEOTHERMAL_C_PER_KM} degC/km (only used to move Rw "
      "between wells).\n"
      "- Bit size 8.5 in where no BS curve exists.\n"
      "- Cutoffs are common screening values, not field-calibrated (see sweep).\n")
    (C.RESULTS / "SUMMARY.md").write_text("\n".join(L))
